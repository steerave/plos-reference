def _seed_monthly_field(
    conn: sqlite3.Connection,
    *,
    slug: str,
    entity_type: str,
    domain: str,
    subdir: str,
    field_name: str,
    rows: list[tuple[str, str]],
    paperless_id_base: int | None = None,
) -> int:
    """Insert (date, value) rows for an arbitrary entity+field combination.

    Used by the expectation-gap tests to seed mortgage / bank / utility
    history for distinct entity types under their respective subdirectories.
    """
    entity_id = _insert_entity(
        conn,
        entity_type=entity_type,
        domain=domain,
        slug=slug,
        wiki_path=f"source/{subdir}/{slug}/index.md",
    )
    if paperless_id_base is None:
        paperless_id_base = 200 + abs(hash(slug + field_name)) % 9000
    for i, (date_, value) in enumerate(rows):
        doc_id = _insert_document(
            conn,
            paperless_id=paperless_id_base + i,
            paperless_url=(
                f"http://localhost:8888/documents/{paperless_id_base + i}/"
            ),
            document_date=date_,
        )
        _insert_field(
            conn,
            document_id=doc_id,
            entity_id=entity_id,
            field_name=field_name,
            field_value=value,
            source_document_date=date_,
        )
    return entity_id


