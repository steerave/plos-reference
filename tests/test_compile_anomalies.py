def test_compute_expectation_gaps_sorted_by_days_overdue_desc(conn):
    """Two gaps with different last-seen ages — fresher gap appears second."""
    _seed_monthly_field(
        conn,
        slug="123-main",
        entity_type="property",
        domain="properties",
        subdir="properties",
        field_name="last_utility_bill_amount",
        rows=[("2026-04-15", "100")],
    )
    _seed_monthly_field(
        conn,
        slug="acct-checking",
        entity_type="account",
        domain="finance",
        subdir="accounts",
        field_name="last_statement_balance",
        rows=[("2026-03-16", "16529.74")],
    )
    gaps = compile_anomalies.compute_expectation_gaps(
        conn, as_of=date(2026, 6, 21)
    )
    # Both miss June — both are 1 day overdue past June 20. Tie-break:
    # entity_slug alphabetic — acct-checking < 123-main? Actually "1" < "a"
    # in ASCII, so 123-main comes first. The sort key is (-days_overdue,
    # entity_slug, field_name), so both have days_overdue=1 and sort by slug.
    assert len(gaps) == 2
