def test_build_manifest_includes_all_entity_index_files(vault):
    manifest = compile_this_week.build_manifest(vault)
    assert "/source/properties/123-main-davenport/index.md" in manifest
    assert "/source/accounts/first-davenport-checking-4521/index.md" in manifest
    assert "/source/people/joe/index.md" in manifest


def test_build_manifest_includes_dashboards(vault):
    manifest = compile_this_week.build_manifest(vault)
    assert "/dashboards/properties.md" in manifest


def test_build_manifest_includes_previous_output_if_present(vault):
    _write(vault / "compiled" / "this-week.md", "previous content here")
    manifest = compile_this_week.build_manifest(vault)
    assert "/compiled/this-week.md" in manifest
    assert "previous content here" in manifest


def test_build_manifest_omits_previous_output_when_absent(vault):
    """Bare vault — no previous output exists yet."""
    manifest = compile_this_week.build_manifest(vault)
    assert "Previous compile output" not in manifest


def test_build_manifest_includes_todays_date(vault):
    manifest = compile_this_week.build_manifest(vault)
    # Format: "Today's date (UTC): YYYY-MM-DD"
    assert "Today's date (UTC):" in manifest


