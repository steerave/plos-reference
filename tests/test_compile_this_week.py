def test_run_invokes_claude_with_prompt_on_stdin(vault, monkeypatch):
    captured = {}

    def fake_run(cmd, **kwargs):
        captured["cmd"] = cmd
        captured["input"] = kwargs.get("input")
        captured["kwargs"] = kwargs
        return subprocess.CompletedProcess(cmd, 0, VALID_MOCK_RESPONSE, "")

    monkeypatch.setattr(subprocess, "run", fake_run)
    compile_this_week.run(vault)

    assert captured["cmd"][0] == "claude"
    assert "--print" in captured["cmd"]
    # Manifest content reaches the subprocess
    assert "/source/people/joe/index.md" in captured["input"]
    # Preamble reaches the subprocess too
    assert "this-week.md" in captured["input"]
    assert captured["kwargs"]["text"] is True
    assert captured["kwargs"]["check"] is True
    # UTF-8 encoding is required on Windows: both the prompt and
    # Claude's response carry → arrows that cp1252 can't handle.
    assert captured["kwargs"]["encoding"] == "utf-8"


def test_run_writes_claude_output_atomically(vault, monkeypatch):
    monkeypatch.setattr(
        subprocess,
        "run",
        lambda *a, **kw: subprocess.CompletedProcess(a[0], 0, VALID_MOCK_RESPONSE, ""),
    )
    target = compile_this_week.run(vault)

    assert target == vault / "compiled" / "this-week.md"
    assert target.read_text(encoding="utf-8") == VALID_MOCK_RESPONSE
    # No temp file leak
    leftover = list(target.parent.glob("*.tmp"))
    assert leftover == []


def test_run_overwrites_existing_compiled_output(vault, monkeypatch):
    target = vault / "compiled" / "this-week.md"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("STALE", encoding="utf-8")

    monkeypatch.setattr(
        subprocess,
        "run",
        lambda *a, **kw: subprocess.CompletedProcess(a[0], 0, VALID_MOCK_RESPONSE, ""),
    )
    compile_this_week.run(vault)

    assert target.read_text(encoding="utf-8") == VALID_MOCK_RESPONSE
    assert "STALE" not in target.read_text(encoding="utf-8")


def test_run_rejects_response_without_frontmatter(vault, monkeypatch):
    """Malformed Claude output must not corrupt an existing compiled artifact."""
    target = vault / "compiled" / "this-week.md"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("EXISTING", encoding="utf-8")

    monkeypatch.setattr(
        subprocess,
        "run",
        lambda *a, **kw: subprocess.CompletedProcess(
            a[0], 0, "I can't help with that.", ""
        ),
    )
    with pytest.raises(ValueError, match="frontmatter"):
        compile_this_week.run(vault)

    # Existing file untouched
    assert target.read_text(encoding="utf-8") == "EXISTING"


def test_run_rejects_response_missing_required_sections(vault, monkeypatch):
    """Response with frontmatter but missing 'Must do' must not be written."""
    monkeypatch.setattr(
        subprocess,
        "run",
        lambda *a, **kw: subprocess.CompletedProcess(
            a[0], 0, "---\ntype: compiled\n---\n# Header only\n", ""
        ),
    )
    with pytest.raises(ValueError, match="Must do"):
        compile_this_week.run(vault)

    assert not (vault / "compiled" / "this-week.md").exists()


def test_run_propagates_subprocess_failure(vault, monkeypatch):
    """If the claude CLI exits non-zero, the run raises and no file is written."""

    def fake_run(cmd, **kwargs):
        raise subprocess.CalledProcessError(1, cmd, "", "claude: not found")

    monkeypatch.setattr(subprocess, "run", fake_run)
    with pytest.raises(subprocess.CalledProcessError):
        compile_this_week.run(vault)

    assert not (vault / "compiled" / "this-week.md").exists()


