"""
Tests for the this-week.md compile pass.

The actual Claude CLI invocation is mocked — we test the wiring (manifest
building, atomic write, format-validation gate) and not the prompt's
effectiveness against a live LLM.
"""

from __future__ import annotations

import subprocess
from pathlib import Path

import pytest

from plos import compile_this_week


# -----------------------------------------------------------------------------
# Helpers
# -----------------------------------------------------------------------------


def _write(path: Path, content: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return path


@pytest.fixture
def vault(tmp_path: Path) -> Path:
    """Build a tmp vault with one of each entity type plus one dashboard."""
    root = tmp_path / "vault"
    _write(
        root / "source" / "properties" / "123-main-davenport" / "index.md",
        "---\nentity: property\nslug: 123-main-davenport\n"
        "insurance_renewal_date: '2026-05-22'\n---\n# 123 Main\n",
    )
    _write(
        root / "source" / "accounts" / "first-davenport-checking-4521" / "index.md",
        "---\nentity: account\nslug: first-davenport-checking-4521\n---\n"
        "# Checking ...4521\n",
    )
    _write(
        root / "source" / "people" / "joe" / "index.md",
        "---\nentity: person\nslug: joe\n"
        "drivers_license_expiry: '2026-05-15'\n---\n# Joe Sample\n",
    )
    _write(
        root / "dashboards" / "properties.md",
        "---\ntype: dashboard\ndashboard: properties\n---\n# Properties\n",
    )
    return root


VALID_MOCK_RESPONSE = """\
---
type: compiled
artifact: this-week
refreshed: 2026-05-11T12:00:00Z
refresh_cadence: daily
sources_read:
  - /source/people/joe/index.md
  - /source/properties/123-main-davenport/index.md
compile_pass_version: 1
---

# This Week — May 11 – May 17, 2026

## Must do

- **Drivers license expiry — Joe.** Renew before May 15.
  → /source/people/joe/index.md

## Should do

- _(nothing this week)_

## Watching

- **State Farm renewal.** Coming up May 22.
  → /source/properties/123-main-davenport/index.md

---
*Generated by daily compile pass. To regenerate: `compile this-week`.*
"""


