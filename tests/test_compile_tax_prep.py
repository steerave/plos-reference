"""
Tests for the tax-prep.md compile pass.

The Claude CLI invocation is mocked. We test:
- The inventory-parsing logic (`compute_tax_prep`) end-to-end against
  a temp vault with a real expected-documents.md.
- The wiring (`build_manifest`, `_validate_response`, atomic write,
  inventory-missing short-circuit).

Per CLAUDE.md Phase 5 Slice 3 conventions, the inventory file is the
single source of truth for what's expected vs. received; the
`received: bool` flag is the partitioning signal. Tests reflect that
split: parsing/categorization is exercised against synthetic
inventories; Claude's prose is mocked.
"""

from __future__ import annotations

import subprocess
from datetime import date
from pathlib import Path

import pytest

from plos import compile_tax_prep


# -----------------------------------------------------------------------------
# Helpers
# -----------------------------------------------------------------------------


def _write(path: Path, content: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return path


@pytest.fixture
def vault(tmp_path: Path) -> Path:
    """Empty vault scaffold; tests seed inventories as needed."""
    root = tmp_path / "vault"
    root.mkdir()
    return root


SAMPLE_INVENTORY = """\
---
type: tax-expected
tax_year: 2026
expected:
  - name: W-2 from Beacon Software
    source: employer
    received: false
    notes: arrives mid-January
  - name: 1098 mortgage interest from Mr. Cooper
    source: mortgage servicer
    received: true
    received_date: 2026-01-28
    received_path: source/tax/2026/received/1098_mr_cooper.pdf
  - name: 1099-INT from First Davenport Bank
    source: bank
    received: false
  - name: Property tax statement (123 Main St)
    source: county assessor
    received: true
    received_date: 2026-04-15
    received_path: source/tax/2026/received/property_tax_2026.pdf
---

# Expected tax documents — 2026

Free-form prose for humans.
"""


VALID_MOCK_RESPONSE = """\
---
type: compiled
artifact: tax-prep
refreshed: 2026-05-10T12:00:00Z
tax_year: 2026
refresh_cadence: monthly (weekly Jan-Apr)
sources_read:
  - /source/tax/2026/expected-documents.md
compile_pass_version: 1
---

# Tax Prep — Tax Year 2026

**Status:** 2 of 4 expected documents received.

## Received

- 1098 mortgage interest from Mr. Cooper. Received 2026-01-28.
  → /source/tax/2026/received/1098_mr_cooper.pdf
- Property tax statement (123 Main St). Received 2026-04-15.
  → /source/tax/2026/received/property_tax_2026.pdf

## Missing

- **W-2 from Beacon Software.** Employer; arrives mid-January.
  → /source/tax/2026/expected-documents.md
- **1099-INT from First Davenport Bank.** Bank.
  → /source/tax/2026/expected-documents.md

---
*Generated by monthly tax-prep compile pass. To regenerate: `compile tax-prep`.*
"""


# -----------------------------------------------------------------------------
# _default_tax_year — calendar math
# -----------------------------------------------------------------------------


def test_default_tax_year_during_filing_window_returns_prior_year():
    """Jan-Apr is the filing window for the previous year."""
    assert compile_tax_prep._default_tax_year(date(2026, 1, 5)) == 2025
    assert compile_tax_prep._default_tax_year(date(2026, 4, 15)) == 2025
    assert compile_tax_prep._default_tax_year(date(2026, 4, 30)) == 2025


def test_default_tax_year_outside_filing_window_returns_current_year():
    """May-Dec is the collection window for the current year."""
    assert compile_tax_prep._default_tax_year(date(2026, 5, 1)) == 2026
    assert compile_tax_prep._default_tax_year(date(2026, 12, 31)) == 2026


# -----------------------------------------------------------------------------
# compute_tax_prep — parsing + categorization
# -----------------------------------------------------------------------------


def test_compute_tax_prep_returns_none_when_inventory_missing(vault):
    """No file at source/tax/<year>/expected-documents.md → None."""
    assert (
        compile_tax_prep.compute_tax_prep(vault, tax_year=2026) is None
    )


def test_compute_tax_prep_partitions_received_vs_missing(vault):
    _write(vault / "source" / "tax" / "2026" / "expected-documents.md", SAMPLE_INVENTORY)
    result = compile_tax_prep.compute_tax_prep(vault, tax_year=2026)
    assert result is not None
    assert result.tax_year == 2026
    assert len(result.received) == 2
    assert len(result.missing) == 2

    received_names = [d.name for d in result.received]
    assert "1098 mortgage interest from Mr. Cooper" in received_names
    assert "Property tax statement (123 Main St)" in received_names

    missing_names = [d.name for d in result.missing]
    assert "W-2 from Beacon Software" in missing_names
    assert "1099-INT from First Davenport Bank" in missing_names


def test_compute_tax_prep_preserves_entry_metadata(vault):
    _write(vault / "source" / "tax" / "2026" / "expected-documents.md", SAMPLE_INVENTORY)
    result = compile_tax_prep.compute_tax_prep(vault, tax_year=2026)
    assert result is not None

    cooper = next(d for d in result.received if "Mr. Cooper" in d.name)
    assert cooper.source == "mortgage servicer"
    assert cooper.received_date == "2026-01-28"
    assert cooper.received_path == "source/tax/2026/received/1098_mr_cooper.pdf"

    w2 = next(d for d in result.missing if "W-2" in d.name)
    assert w2.source == "employer"
    assert w2.received is False
    assert w2.notes == "arrives mid-January"
    assert w2.received_date is None
    assert w2.received_path is None


def test_compute_tax_prep_empty_expected_list_returns_empty_lists(vault):
    """An inventory file with `expected: []` is a valid empty inventory."""
    _write(
        vault / "source" / "tax" / "2026" / "expected-documents.md",
        "---\ntype: tax-expected\ntax_year: 2026\nexpected: []\n---\n\n# 2026\n",
    )
    result = compile_tax_prep.compute_tax_prep(vault, tax_year=2026)
    assert result is not None
    assert result.received == []
    assert result.missing == []


def test_compute_tax_prep_skips_non_dict_entries(vault):
    """A scalar (e.g. just a string) in the `expected:` list is ignored."""
    _write(
        vault / "source" / "tax" / "2026" / "expected-documents.md",
        "---\nexpected:\n  - W-2\n  - {name: 1099, received: true}\n---\n",
    )
    result = compile_tax_prep.compute_tax_prep(vault, tax_year=2026)
    assert result is not None
    # Only the dict entry lands
    assert len(result.received) == 1
    assert len(result.missing) == 0
    assert result.received[0].name == "1099"


def test_compute_tax_prep_treats_missing_received_flag_as_false(vault):
    """An entry with no `received:` key is treated as missing."""
    _write(
        vault / "source" / "tax" / "2026" / "expected-documents.md",
        "---\nexpected:\n  - name: W-2\n  - {name: 1099, received: true}\n---\n",
    )
    result = compile_tax_prep.compute_tax_prep(vault, tax_year=2026)
    assert result is not None
    assert len(result.received) == 1
    assert len(result.missing) == 1
    assert result.missing[0].name == "W-2"


def test_compute_tax_prep_uses_default_year_from_as_of(vault):
    """Resolves tax_year from as_of when caller passes neither."""
    _write(vault / "source" / "tax" / "2025" / "expected-documents.md", SAMPLE_INVENTORY)
    # February 2026 → filing window for 2025
    result = compile_tax_prep.compute_tax_prep(vault, as_of=date(2026, 2, 1))
    assert result is not None
    assert result.tax_year == 2025


def test_compute_tax_prep_explicit_tax_year_overrides_as_of(vault):
    _write(vault / "source" / "tax" / "2026" / "expected-documents.md", SAMPLE_INVENTORY)
    # February 2026 would default to 2025, but explicit override wins.
    result = compile_tax_prep.compute_tax_prep(
        vault, tax_year=2026, as_of=date(2026, 2, 1)
    )
    assert result is not None
    assert result.tax_year == 2026


