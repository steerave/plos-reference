def test_run_short_circuits_when_no_inventory_file(vault, monkeypatch):
    """No inventory → write deterministic 'no inventory configured' artifact."""

    def fake_run(*args, **kwargs):
        raise AssertionError(
            "subprocess.run must not be invoked when inventory is missing"
        )

    monkeypatch.setattr(subprocess, "run", fake_run)
    target = compile_tax_prep.run(vault, tax_year=2026)

    body = target.read_text(encoding="utf-8")
    assert body.startswith("---\n")
    assert "artifact: tax-prep" in body
    assert "tax_year: 2026" in body
    assert "## Received" in body
    assert "## Missing" in body
    assert "no inventory configured" in body.lower()
    # Atomic write leaves no temp file
    assert list(target.parent.glob("*.tmp")) == []


