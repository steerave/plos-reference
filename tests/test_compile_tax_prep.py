def test_build_manifest_includes_counts_and_year(vault):
    _write(vault / "source" / "tax" / "2026" / "expected-documents.md", SAMPLE_INVENTORY)
    result = compile_tax_prep.compute_tax_prep(vault, tax_year=2026)
    manifest = compile_tax_prep.build_manifest(vault, result)
    assert "Tax year: 2026" in manifest
    assert "Received count: 2" in manifest
    assert "Missing count: 2" in manifest
    assert "Total count: 4" in manifest


def test_build_manifest_renders_both_lists_with_entry_metadata(vault):
    _write(vault / "source" / "tax" / "2026" / "expected-documents.md", SAMPLE_INVENTORY)
    result = compile_tax_prep.compute_tax_prep(vault, tax_year=2026)
    manifest = compile_tax_prep.build_manifest(vault, result)
    assert "## Received entries" in manifest
    assert "## Missing entries" in manifest
    assert "name: 1098 mortgage interest from Mr. Cooper" in manifest
    assert "received_path: /source/tax/2026/received/1098_mr_cooper.pdf" in manifest
    assert "notes: arrives mid-January" in manifest
    # Inventory file is bundled as provenance
    assert "/source/tax/2026/expected-documents.md" in manifest
    assert "type: tax-expected" in manifest


def test_build_manifest_renders_empty_lists_with_marker(vault):
    _write(
        vault / "source" / "tax" / "2026" / "expected-documents.md",
        "---\nexpected: []\n---\n",
    )
    result = compile_tax_prep.compute_tax_prep(vault, tax_year=2026)
    manifest = compile_tax_prep.build_manifest(vault, result)
    assert "Received count: 0" in manifest
    assert "Missing count: 0" in manifest
    # Each empty section heading gets a `_(none)_` marker
    assert manifest.count("_(none)_") == 2


